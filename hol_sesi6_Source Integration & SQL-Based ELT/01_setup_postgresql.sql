CREATE TABLE s6_mart.dim_product (
 product_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_code TEXT NOT NULL UNIQUE,product_name TEXT NOT NULL);
CREATE TABLE s6_mart.dim_participant (
 participant_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 participant_id INTEGER NOT NULL UNIQUE,participant_name TEXT NOT NULL,city TEXT NOT NULL);
CREATE TABLE s6_mart.dim_policy (
 policy_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 policy_id INTEGER NOT NULL UNIQUE,policy_number TEXT NOT NULL UNIQUE);
CREATE TABLE s6_mart.dim_date (
 date_key INTEGER PRIMARY KEY,calendar_date DATE NOT NULL UNIQUE);
CREATE TABLE s6_mart.fact_contribution_receipt (
 contribution_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_system TEXT NOT NULL,event_id INTEGER NOT NULL,
 contribution_date_key INTEGER NOT NULL REFERENCES s6_mart.dim_date(date_key),
 product_key INTEGER NOT NULL REFERENCES s6_mart.dim_product(product_key),
 policy_key INTEGER NOT NULL REFERENCES s6_mart.dim_policy(policy_key),
 participant_key INTEGER NOT NULL REFERENCES s6_mart.dim_participant(participant_key),
 amount NUMERIC(15,2) NOT NULL CHECK(amount>0),
 transaction_count INTEGER NOT NULL DEFAULT 1 CHECK(transaction_count=1),
 UNIQUE(source_system,event_id));
CREATE TABLE s6_mart.fact_claim_payment (
 claim_payment_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_system TEXT NOT NULL,event_id INTEGER NOT NULL,
 payment_date_key INTEGER NOT NULL REFERENCES s6_mart.dim_date(date_key),
 product_key INTEGER NOT NULL REFERENCES s6_mart.dim_product(product_key),
 policy_key INTEGER NOT NULL REFERENCES s6_mart.dim_policy(policy_key),
 participant_key INTEGER NOT NULL REFERENCES s6_mart.dim_participant(participant_key),
 amount NUMERIC(15,2) NOT NULL CHECK(amount>0),
 paid_claim_count INTEGER NOT NULL DEFAULT 1 CHECK(paid_claim_count=1),
 UNIQUE(source_system,event_id));
