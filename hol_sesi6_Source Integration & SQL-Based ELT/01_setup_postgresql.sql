CREATE SCHEMA s6_staging;
CREATE SCHEMA s6_mart;
CREATE TABLE s6_staging.product (
 product_id INTEGER PRIMARY KEY,
 product_code VARCHAR(20),
 product_name VARCHAR(80)
);

CREATE TABLE s6_staging.participant (
 participant_id INTEGER PRIMARY KEY,
 participant_name VARCHAR(80),
 city VARCHAR(40)
);

CREATE TABLE s6_staging.policy (
 policy_id INTEGER PRIMARY KEY,
 policy_number VARCHAR(30),
 product_code VARCHAR(20),
 participant_id INTEGER
);

CREATE TABLE s6_staging.contribution (
 event_id INTEGER PRIMARY KEY,
 policy_id INTEGER,
 event_date DATE,
 amount NUMERIC(15,2),
 status VARCHAR(20)
);

CREATE TABLE s6_staging.claim (
 event_id INTEGER PRIMARY KEY,
 policy_id INTEGER,
 submitted_date DATE,
 paid_date DATE,
 paid_amount NUMERIC(15,2),
 status VARCHAR(20)
);

